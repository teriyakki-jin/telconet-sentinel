@pytest.mark.parametrize(
    "raw_mutation",
    [
        '"source": "duplicate",\n  ',
        '"configured_detection_ms": NaN,\n      ',
    ],
)
def test_report_rejects_ambiguous_or_non_finite_json(
    tmp_path: Path,
    raw_mutation: str,
) -> None:
    raw = COMPARISON.read_text(encoding="utf-8")
    if "source" in raw_mutation:
        altered_raw = raw.replace('"improvement": {', raw_mutation + '"improvement": {')
    else:
        altered_raw = raw.replace(
            '"baseline": {', raw_mutation + '"baseline": {', 1
        )
    altered = tmp_path / "comparison.json"
    altered.write_text(altered_raw, encoding="utf-8")

    with pytest.raises(ValueError, match="duplicate JSON key|non-finite JSON value"):
        render_report_from_paths(
            altered, REPEATED, FAILURE_DOMAINS, project_root=ROOT
        )


