import hashlib
import json
import shutil
from pathlib import Path

import pytest

import telconet_sentinel.report as report_module
from telconet_sentinel.report import main, render_report_from_paths

ROOT = Path(__file__).parents[2]
COMPARISON = ROOT / "evidence" / "bfd-comparison.json"
REPEATED = ROOT / "evidence" / "bfd-repeated-trials.json"
FAILURE_DOMAINS = ROOT / "evidence" / "failure-domain-audit.json"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def test_renders_a_traceable_portfolio_report_from_versioned_evidence() -> None:
    report = render_report_from_paths(
        COMPARISON, REPEATED, FAILURE_DOMAINS, project_root=ROOT
    )

    assert report.startswith("<!-- Generated by telconet-report; do not edit manually. -->")
    assert "# Network Resilience Experiment Report" in report
    assert "## Executive summary" in report
    assert "20 trials per profile" in report
    assert "| OSPF only | 3,794.5 ms | 4,058 ms | 4,158 ms |" in report
    assert "| BFD 100 ms × 3 | 498 ms | 519 ms | 523 ms |" in report
    assert "**87.21%**" in report
    assert "service-entry" in report
    assert "Measured in containerlab" in report
    assert "Modeled from declared failure domains" in report
    assert "not a production SLA" in report
    assert _sha256(COMPARISON) in report
    assert _sha256(REPEATED) in report
    assert _sha256(FAILURE_DOMAINS) in report
    assert report.endswith("\n")


def test_report_rejects_mixed_configuration_fingerprints(tmp_path: Path) -> None:
    repeated = json.loads(REPEATED.read_text(encoding="utf-8"))
    repeated["environment"]["configuration_sha256"] = "0" * 64
    mismatched = tmp_path / "repeated.json"
    mismatched.write_text(json.dumps(repeated), encoding="utf-8")

    with pytest.raises(ValueError, match="configuration fingerprint"):
        render_report_from_paths(
            COMPARISON, mismatched, FAILURE_DOMAINS, project_root=ROOT
        )


