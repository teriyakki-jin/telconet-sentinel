@pytest.mark.parametrize(
    ("evidence_name", "mutation"),
    [
        ("comparison", ("source", "self_declared_measurement")),
        ("comparison", ("limitations", ["https://example.invalid *bold*"])),
        ("repeated", ("improvement.p95_detection_reduction_percent", 99.99)),
    ],
)
def test_report_rejects_measured_evidence_not_recomputed_from_raw_logs(
    tmp_path: Path,
    evidence_name: str,
    mutation: tuple[str, object],
) -> None:
    source_path = COMPARISON if evidence_name == "comparison" else REPEATED
    evidence = json.loads(source_path.read_text(encoding="utf-8"))
    field, value = mutation
    if field == "improvement.p95_detection_reduction_percent":
        evidence["improvement"]["p95_detection_reduction_percent"] = value
    else:
        evidence[field] = value
    altered = tmp_path / source_path.name
    altered.write_text(json.dumps(evidence), encoding="utf-8")

    comparison = altered if evidence_name == "comparison" else COMPARISON
    repeated = altered if evidence_name == "repeated" else REPEATED
    with pytest.raises(
        ValueError, match="source|does not match raw-log recalculation"
    ):
        render_report_from_paths(
            comparison, repeated, FAILURE_DOMAINS, project_root=ROOT
        )


@pytest.mark.parametrize(
    ("mutation", "message"),
    [
        (("design", "unrelated-design"), "does not match recomputed audit"),
        (("summary.outage", 0), "does not match recomputed audit"),
    ],
)
def test_report_rejects_failure_domain_evidence_not_derived_from_current_intent(
    tmp_path: Path,
    mutation: tuple[str, object],
    message: str,
) -> None:
    evidence = json.loads(FAILURE_DOMAINS.read_text(encoding="utf-8"))
    field, value = mutation
    if field == "summary.outage":
        evidence["summary"]["outage"] = value
    else:
        evidence[field] = value
    altered = tmp_path / "failure-domains.json"
    altered.write_text(json.dumps(evidence), encoding="utf-8")

    with pytest.raises(ValueError, match=message):
        render_report_from_paths(
            COMPARISON, REPEATED, altered, project_root=ROOT
        )


