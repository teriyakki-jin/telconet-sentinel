def test_report_cli_rejects_overwriting_an_input(tmp_path: Path) -> None:
    comparison = tmp_path / "comparison.json"
    comparison.write_bytes(COMPARISON.read_bytes())
    original = comparison.read_bytes()

    with pytest.raises(ValueError, match="output must not overwrite an input"):
        main(
            [
                "--comparison",
                str(comparison),
                "--repeated",
                str(REPEATED),
                "--failure-domains",
                str(FAILURE_DOMAINS),
                "--project-root",
                str(ROOT),
                "--output",
                str(comparison),
            ]
        )
    assert comparison.read_bytes() == original


def test_report_cli_rejects_overwriting_an_indirect_raw_log(tmp_path: Path) -> None:
    project_root = tmp_path / "project"
    shutil.copytree(ROOT / "evidence", project_root / "evidence")
    shutil.copytree(ROOT / "lab", project_root / "lab")
    raw_log = project_root / "evidence" / "remote-blackhole-ospf.log"
    original = raw_log.read_bytes()

    with pytest.raises(ValueError, match="output must not overwrite a provenance input"):
        main(
            [
                "--comparison",
                str(project_root / "evidence" / COMPARISON.name),
                "--repeated",
                str(project_root / "evidence" / REPEATED.name),
                "--failure-domains",
                str(project_root / "evidence" / FAILURE_DOMAINS.name),
                "--project-root",
                str(project_root),
                "--output",
                str(raw_log),
            ]
        )
    assert raw_log.read_bytes() == original


def test_report_rejects_excess_trial_files_before_reading_them(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    evidence_directory = tmp_path / "evidence"
    evidence_directory.mkdir()
    for filename in ("remote-blackhole-ospf.log", "remote-blackhole-bfd.log"):
        shutil.copyfile(ROOT / "evidence" / filename, evidence_directory / filename)
    for profile in ("ospf_only", "bfd_100x3"):
        profile_directory = evidence_directory / "repeated" / profile
        profile_directory.mkdir(parents=True)
        for trial in range(1, 32):
            (profile_directory / f"trial-{trial:02d}.log").touch()

    original_reader = report_module._read_raw_log

    def guarded_reader(path: Path) -> str:
        if path.parent.parent.name == "repeated":
            raise AssertionError("trial log was read before count validation")
        return original_reader(path)

    monkeypatch.setattr(report_module, "_read_raw_log", guarded_reader)
    comparison = json.loads(COMPARISON.read_text(encoding="utf-8"))
    repeated = json.loads(REPEATED.read_text(encoding="utf-8"))

    with pytest.raises(ValueError, match="expected 20 trial logs.*found 31"):
        report_module._validate_measured_evidence(
            comparison, repeated, tmp_path
        )


